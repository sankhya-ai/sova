import { existsSync, mkdirSync, readFileSync, writeFileSync } from "node:fs";
import { basename, dirname, join, relative, sep } from "node:path";
import type { SovaConfig } from "./config.js";
import { Blocked, locatorForCall, type LocatorCode } from "./locator.js";
import { readTrail, type ToolCall, type Trail } from "./trail.js";
import { quote, regexLiteral, walk } from "./util.js";

export const GENERATED_MARKER = "// Generated by sova from ";

/** Tools that only read the page. They leave nothing to replay. */
const READ_ONLY_TOOLS = new Set(["web_snapshot", "web_currentUrl", "web_requestDetails"]);

interface CallCode {
  lines: string[];
  warnings: string[];
}

function requireLocator(call: ToolCall, warnings: string[]): LocatorCode {
  const locator = locatorForCall(call.args);
  if (!locator) throw new Blocked(`${call.tool} recorded no selector and no ref`);
  if (locator.quality === "css") warnings.push(`${call.tool} uses a CSS selector; a role or data-testid is sturdier`);
  if (locator.positional) warnings.push(`${call.tool} depends on match order; a unique role name or data-testid is sturdier`);
  return locator;
}

function str(value: unknown): string {
  return typeof value === "string" ? value : value === undefined || value === null ? "" : String(value);
}

const ENV_TEMPLATE = /\{\{env\.([A-Za-z_][A-Za-z0-9_]*)\}\}/g;
const UNIQUE_TEMPLATE = /\{\{unique\.(.+?)\}\}/g;

/** Marks a line that needs a value that is new on every run, so the test gets the `unique` helper. */
const UNIQUE_CALL = "unique(";

/** A readable test title from a trail id: `customers-create-valid` becomes `Customers create valid`. */
export function humanizeTitle(title: string): string {
  if (!/^[a-z0-9]+(?:[-_.][a-z0-9]+)*$/.test(title)) return title;
  const words = title.replace(/[-_.]+/g, " ");
  return words.charAt(0).toUpperCase() + words.slice(1);
}

/** Marks a line that reads a secret, so the spec gets the `env` helper. */
const ENV_CALL = "env(";

/**
 * Code for a recorded string. `{{env.NAME}}` is a secret the flow was driven with; it is read
 * from the environment when the test runs, so it never sits in the trail or the spec.
 */
function textCode(call: ToolCall, value: string): string {
  const uniqueWhole = /^\{\{unique\.(.+?)\}\}$/.exec(value);
  if (uniqueWhole) return `${UNIQUE_CALL}${quote(uniqueWhole[1]!)})`;
  const rest = value.replace(ENV_TEMPLATE, "").replace(UNIQUE_TEMPLATE, "");
  if (/\{\{.+?\}\}/.test(rest)) {
    throw new Blocked(`${call.tool} uses a memory template (${value}); only {{env.NAME}} is supported`);
  }
  if (rest === value) return quote(value);
  const whole = /^\{\{env\.([A-Za-z_][A-Za-z0-9_]*)\}\}$/.exec(value);
  if (whole) return `${ENV_CALL}${quote(whole[1]!)})`;
  const body = value
    .split(/(\{\{env\.[A-Za-z_][A-Za-z0-9_]*\}\}|\{\{unique\..+?\}\})/)
    .map((part) => {
      const match = /^\{\{env\.(.+)\}\}$/.exec(part);
      if (match) return `\${${ENV_CALL}${quote(match[1]!)})}`;
      const fresh = /^\{\{unique\.(.+)\}\}$/.exec(part);
      return fresh ? `\${${UNIQUE_CALL}${quote(fresh[1]!)})}` : part.replace(/[`\\$]/g, "\\$&");
    })
    .join("");
  return `\`${body}\``;
}

function rejectTemplates(call: ToolCall, value: string): void {
  if (/\{\{.+?\}\}/.test(value)) {
    throw new Blocked(`${call.tool} uses a template (${value}) where only fixed text is supported`);
  }
}

/** `url` relative to the configured base when it lives under it, so specs follow `baseURL`. */
export function relativeToBase(url: string, baseURL: string): string {
  const base = baseURL.replace(/\/+$/, "");
  if (base !== "" && (url === base || url.startsWith(`${base}/`) || url.startsWith(`${base}?`) || url.startsWith(`${base}#`))) {
    const rest = url.slice(base.length);
    return rest.startsWith("/") ? rest : `/${rest}`;
  }
  return url;
}

/** Playwright code for one recorded tool call. Throws {@link Blocked} when it cannot be replayed. */
export function emitCall(call: ToolCall, config: Pick<SovaConfig, "baseURL">): CallCode {
  const warnings: string[] = [];
  const { tool, args } = call;
  if (READ_ONLY_TOOLS.has(tool)) return { lines: [], warnings };

  switch (tool) {
    case "web_navigate": {
      const action = str(args.action || "GOTO").toUpperCase();
      if (action === "BACK") return { lines: ["await page.goBack();"], warnings };
      if (action === "FORWARD") return { lines: ["await page.goForward();"], warnings };
      const url = str(args.url);
      if (url === "") throw new Blocked("web_navigate recorded no url");
      rejectTemplates(call, url);
      return { lines: [`await page.goto(${quote(relativeToBase(url, config.baseURL))});`], warnings };
    }
    case "web_click":
      return { lines: [`await ${requireLocator(call, warnings).code}.click();`], warnings };
    case "web_hover":
      return { lines: [`await ${requireLocator(call, warnings).code}.hover();`], warnings };
    case "web_type": {
      const text = textCode(call, str(args.text));
      const method = args.clearFirst === false ? "pressSequentially" : "fill";
      return { lines: [`await ${requireLocator(call, warnings).code}.${method}(${text});`], warnings };
    }
    case "web_selectOption": {
      const values = Array.isArray(args.values) ? args.values.map(str) : [];
      if (values.length === 0) throw new Blocked("web_selectOption recorded no values");
      const value = values.length === 1 ? quote(values[0]!) : `[${values.map(quote).join(", ")}]`;
      return { lines: [`await ${requireLocator(call, warnings).code}.selectOption(${value});`], warnings };
    }
    case "web_pressKey": {
      const key = str(args.key);
      if (key === "") throw new Blocked("web_pressKey recorded no key");
      return { lines: [`await page.keyboard.press(${quote(key)});`], warnings };
    }
    case "web_scroll": {
      const amount = typeof args.amount === "number" ? args.amount : 500;
      const direction = str(args.direction || "DOWN").toUpperCase();
      const [dx, dy] = direction === "UP" ? [0, -amount]
        : direction === "LEFT" ? [-amount, 0]
        : direction === "RIGHT" ? [amount, 0]
        : [0, amount];
      const lines: string[] = [];
      const target = locatorForCall(args);
      if (target) lines.push(`await ${target.code}.hover();`);
      lines.push(`await page.mouse.wheel(${dx}, ${dy});`);
      return { lines, warnings };
    }
    case "web_wait":
      // Web-first assertions and actions wait on their own; a fixed sleep only adds flake.
      warnings.push("dropped a fixed web_wait; Playwright actions and assertions auto-wait");
      return { lines: [], warnings };
    case "web_waitForUrl": {
      const pattern = regexLiteral(str(args.pattern));
      if (pattern === null || str(args.pattern) === "") {
        throw new Blocked(`web_waitForUrl pattern ${JSON.stringify(args.pattern)} is not a valid JavaScript regex`);
      }
      return { lines: [`await expect(page).toHaveURL(${pattern});`], warnings };
    }
    case "web_verifyElementVisible":
      return { lines: [`await expect(${requireLocator(call, warnings).code}).toBeVisible();`], warnings };
    case "web_verifyValue": {
      const locator = requireLocator(call, warnings).code;
      const expected = textCode(call, str(args.expected));
      const type = str(args.type || "TEXT").toUpperCase();
      if (type === "VALUE") return { lines: [`await expect(${locator}).toHaveValue(${expected});`], warnings };
      if (type === "ATTRIBUTE") {
        const attribute = str(args.attribute);
        if (attribute === "") throw new Blocked("web_verifyValue of type ATTRIBUTE recorded no attribute name");
        return { lines: [`await expect(${locator}).toHaveAttribute(${quote(attribute)}, ${expected});`], warnings };
      }
      return { lines: [`await expect(${locator}).toContainText(${expected});`], warnings };
    }
    case "web_verifyListVisible": {
      const items = Array.isArray(args.items) ? args.items.map(str) : [];
      if (items.length === 0) throw new Blocked("web_verifyListVisible recorded no items");
      const container = locatorForCall(args)?.code ?? "page";
      return {
        lines: items.map((item) => `await expect(${container}.getByText(${quote(item)}).first()).toBeVisible();`),
        warnings,
      };
    }
    default:
      if (tool.startsWith("web_")) throw new Blocked(`${tool} is not supported by the emitter yet`);
      throw new Blocked(
        `${tool} is a custom tool; sova only sees recorded web_* calls, so record this flow with primitives`,
      );
  }
}

export interface EmitResult {
  /** The spec source, or null when the trail is skipped or blocked. */
  spec: string | null;
  status: "emitted" | "skipped" | "blocked";
  /** Why the trail was skipped or blocked. */
  reason?: string;
  warnings: string[];
  assertions: number;
}

/** Turn one parsed trail into a Playwright spec. */
/** The environment variable that holds a role's saved session file. */
export function stateEnv(role: string): string {
  return `SOVA_AUTH_STATE_${role.toUpperCase().replace(/[^A-Z0-9]/g, "_")}`;
}

export function emitTrail(
  trail: Trail,
  sourceLabel: string,
  fallbackTitle: string,
  config: Pick<SovaConfig, "baseURL"> & { fixturesImport?: string },
  role: "test" | "login" | "anonymous" = "test",
  session: { saveEnv?: string; useEnv?: string } = {},
): EmitResult {
  const warnings: string[] = [];
  if (!trail.isWeb) return { spec: null, status: "skipped", reason: "not a web trail", warnings, assertions: 0 };

  const blocks: string[] = [];
  let assertions = 0;
  for (const [index, step] of trail.steps.entries()) {
    const where = `step ${index + 1} (${JSON.stringify(step.text)})`;
    if (step.calls === null || step.calls.length === 0) {
      return {
        spec: null,
        status: "blocked",
        reason: `${where} has no web recording; replay it with Trailblaze so the step is recorded`,
        warnings,
        assertions,
      };
    }
    const lines: string[] = [];
    for (const call of step.calls) {
      try {
        const code = emitCall(call, config);
        lines.push(...code.lines);
        warnings.push(...code.warnings.map((warning) => `step ${index + 1}: ${warning}`));
      } catch (error) {
        if (error instanceof Blocked) {
          return { spec: null, status: "blocked", reason: `${where}: ${error.message}`, warnings, assertions };
        }
        throw error;
      }
    }
    if (lines.length === 0) continue;
    assertions += lines.filter((line) => line.includes("expect(")).length;
    blocks.push(
      `  await test.step(${quote(step.text)}, async () => {\n` +
        lines.map((line) => `    ${line}`).join("\n") +
        "\n  });",
    );
  }
  if (blocks.length === 0) {
    return { spec: null, status: "blocked", reason: "the trail has no replayable steps", warnings, assertions };
  }

  const title = humanizeTitle(trail.title ?? fallbackTitle);
  const tags = trail.tags.map((tag) => (tag.startsWith("@") ? tag : `@${tag}`));
  const details = tags.length > 0 ? `{ tag: [${tags.map(quote).join(", ")}] }, ` : "";
  if (role === "login") {
    // The session this flow leaves is what every other test starts from. Firebase and
    // similar keep theirs in IndexedDB, so that is saved along with cookies and storage.
    blocks.push(
      "  await test.step('Keep the signed-in session for the other tests', async () => {\n" +
        "    await page.context().storageState({ path: process.env." + (session.saveEnv ?? "SOVA_AUTH_STATE") + "!, indexedDB: true });\n" +
        "  });",
    );
  }
  const body = blocks.join("\n\n");
  const helpers =
    (body.includes(ENV_CALL)
      ? "/** A secret the flow was driven with. Set it in the environment or in sova/.env. */\n" +
        "function env(name: string): string {\n" +
        "  const value = process.env[name];\n" +
        "  if (value === undefined) throw new Error(`${name} is not set. Add it to sova/.env or the environment.`);\n" +
        "  return value;\n" +
        "}\n\n"
      : "") +
    (body.includes(UNIQUE_CALL)
      ? "/** A value that is new on every run (an email, a name), so a second run does not collide with the first. */\n" +
        "function makeUnique(): (base: string) => string {\n" +
        "  const seen = new Map<string, string>();\n" +
        "  return (base) => {\n" +
        "    const known = seen.get(base);\n" +
        "    if (known) return known;\n" +
        "    const tag = Math.random().toString(36).slice(2, 8);\n" +
        "    const at = base.indexOf('@');\n" +
        "    const value = at === -1 ? `${base}-${tag}` : `${base.slice(0, at)}+${tag}${base.slice(at)}`;\n" +
        "    seen.set(base, value);\n" +
        "    return value;\n" +
        "  };\n" +
        "}\n\n"
      : "") +
    (role === "login" || role === "anonymous"
      ? "// Starts signed out, whatever session the rest of the suite shares.\n" +
        "test.use({ storageState: { cookies: [], origins: [] } });\n\n"
      : session.useEnv
        ? `// Starts from the ${session.useEnv.replace("SOVA_AUTH_STATE_", "").toLowerCase()} session, not the default one.\n` +
          `test.use({ storageState: process.env.${session.useEnv}! });\n\n`
        : "");
  const spec =
    `${GENERATED_MARKER}${sourceLabel}\n` +
    "// Do not edit. Change the trail, then run `sova emit`.\n" +
    `import { expect, test } from ${quote(config.fixturesImport ?? "@playwright/test")};\n\n` +
    helpers +
    `test(${quote(title)}, ${details}async ({ page }) => {\n` +
    (body.includes(UNIQUE_CALL) ? "  const unique = makeUnique();\n\n" : "") +
    body +
    "\n});\n";
  return { spec, status: "emitted", warnings, assertions };
}

/** Whether `path` is a unified trail file: `trail.yaml` or `<name>.trail.yaml`. */
export function isTrailFile(path: string): boolean {
  const name = basename(path);
  return name === "trail.yaml" || name.endsWith(".trail.yaml");
}

/** `trails/auth/login/trail.yaml` and `trails/auth/login.trail.yaml` both become `auth/login`. */
export function trailId(trailPath: string, trailsDir: string): string {
  const rel = relative(trailsDir, trailPath);
  const id = basename(rel) === "trail.yaml" ? dirname(rel) : rel.replace(/\.trail\.yaml$/, "");
  return id.split(sep).join("/");
}

export interface EmittedFile {
  trailPath: string;
  id: string;
  specPath: string;
  result: EmitResult;
  /** True when the spec on disk already matches what emit produces. */
  upToDate: boolean;
}

export interface EmitRun {
  files: EmittedFile[];
  /** Generated specs whose trail no longer exists or no longer emits. */
  orphans: string[];
}

/**
 * Emit every trail under the configured trails directory. With `write: false` nothing is
 * written, and each file reports whether the spec on disk is current.
 */
export function emitAll(root: string, config: SovaConfig, write: boolean): EmitRun {
  const trailsDir = join(root, config.trailsDir);
  const specsDir = join(root, config.specsDir);
  const files: EmittedFile[] = [];
  const expected = new Set<string>();
  // sova/fixtures.ts, when present, is where the suite's fixtures and cleanup live; specs import `test` from it.
  const fixturesFile = join(root, "sova", "fixtures.ts");
  const fixturesImport = existsSync(fixturesFile)
    ? (() => {
        const rel = relative(specsDir, fixturesFile).split(sep).join("/").replace(/\.ts$/, "");
        return rel.startsWith(".") ? rel : `./${rel}`;
      })()
    : undefined;

  for (const trailPath of walk(trailsDir, isTrailFile)) {
    const id = trailId(trailPath, trailsDir);
    const login = config.login;
    const roleLogin = Object.entries(login?.roles ?? {}).find(([, r]) => r.trail === id)?.[0];
    const asRole = login?.as?.[id];
    const role = id === login?.trail || roleLogin ? "login" : login?.anonymous?.includes(id) ? "anonymous" : "test";
    const session = roleLogin
      ? { saveEnv: stateEnv(roleLogin) }
      : asRole
        ? { useEnv: stateEnv(asRole) }
        : {};
    // The sign-in flow is a Playwright setup file: it runs before the tests that depend on it.
    const specPath = join(specsDir, `${id}.${role === "login" ? "setup" : "spec"}.ts`);
    let result: EmitResult;
    try {
      const label = relative(root, trailPath).split(sep).join("/");
      result = emitTrail(readTrail(trailPath), label, id, { ...config, fixturesImport }, role, session);
    } catch (error) {
      result = { spec: null, status: "blocked", reason: (error as Error).message, warnings: [], assertions: 0 };
    }
    let upToDate = false;
    if (result.spec !== null) {
      expected.add(specPath);
      // Git on Windows may check specs out with CRLF endings; that is not a content change.
      upToDate = existsSync(specPath) && readFileSync(specPath, "utf8").replace(/\r\n/g, "\n") === result.spec;
      if (write && !upToDate) {
        mkdirSync(dirname(specPath), { recursive: true });
        writeFileSync(specPath, result.spec);
      }
    }
    files.push({ trailPath, id, specPath, result, upToDate });
  }

  const orphans = walk(specsDir, (path) => path.endsWith(".spec.ts") || path.endsWith(".setup.ts")).filter(
    (path) => !expected.has(path) && readFileSync(path, "utf8").startsWith(GENERATED_MARKER),
  );
  return { files, orphans };
}
